"""Build the inactive Activity helper asset from its canonical reviewed sources."""
import argparse
import hashlib
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT/'contracts/sonda-activity/candidate-v1'
TARGET = ROOT/'apps/backend/app/sonda_activity_runtime.py'


def rendered():
    spec = importlib.util.spec_from_file_location('sonda_activity_native_builder', CONTRACT/'native_bundle.py')
    builder = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(builder)
    sources = [(CONTRACT/name).read_text(encoding='utf-8') for name in
        ('reference.py','producer.py','public_stream.py')]
    source = builder.bundle_source(*sources,journal_source=(CONTRACT/'journal.py').read_text(encoding='utf-8'),
        results_source=(CONTRACT/'results.py').read_text(encoding='utf-8'))
    source+='\nACTIVITY_MANIFEST_SHA256 = '+repr(hashlib.sha256((CONTRACT/'candidate.json').read_bytes()).hexdigest())+'\n'
    return ('# Generated by scripts/render_sonda_activity.py; edit the canonical contract sources.\n'
        '# Inactive helper asset; installed pack integration and activation require separate acceptance.\n'+source).encode('utf-8')


def render(check=False):
    raw = rendered()
    if check:
        if not TARGET.is_file() or TARGET.read_bytes()!=raw:
            raise SystemExit('Regenerate the inactive Sonda Activity helper asset')
    else:
        TARGET.write_bytes(raw)
    print('Inactive Sonda Activity helper '+('verified' if check else 'rendered')+'; no pack or runtime activation')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    render(parser.parse_args().check)
