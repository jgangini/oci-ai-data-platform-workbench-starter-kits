def upsert_posts(connection, records, analysis_status, ingested_at=None, batch_key=None):
    """Project durable capture/ingestion/analysis progress without replacing a later state."""
    if isinstance(connection, ObjectControlStore):
        return control_store.upsert_posts(connection, records, analysis_status, ingested_at, batch_key)
    if analysis_status not in {"captured", "ingested", "processed"}:
        raise ValueError("Invalid post analysis status")
    documents = {}
    for record in records:
        if record.get("mode") == "simulation":
            record = {**record, "mode": canonical_mode(record["mode"])}
        key = f"{record['platform']}:{record['source_id']}"
        if (len(key) > 200 or not record["source_id"] or not isinstance(record.get("created_at"), str)
                or not re.fullmatch(r"[a-z][a-z0-9_]{0,49}", record["platform"])):
            raise ValueError("Invalid post projection identity")
        document = {**record, "id": key}
        document["listing_published_at"] = published_time(record.get("created_at"))
        captured_at = record.get("captured_at") or (ingested_at if analysis_status == "captured" else None)
        if captured_at is None and record.get("mode") == "real":
            captured_at = record.get("observed_at")
        document.update({name: value for name, value in (("captured_at", captured_at), ("ingested_at", ingested_at), ("batch_key", batch_key))
                         if value is not None})
        documents[key] = document
    if not documents:
        return
    payload = json.dumps(list(documents.values()), ensure_ascii=False, allow_nan=False)
    cursor = connection.cursor()
    try:
        cursor.callproc("ADMIN.PRISMA_CONTROL.UPSERT_POSTS", [payload, analysis_status])
    except Exception as exc:
        # Concurrent VM/stream inserts may race once; the second MERGE observes the winner.
        if not exc.args or getattr(exc.args[0], "code", None) != 1:
            raise
        cursor.callproc("ADMIN.PRISMA_CONTROL.UPSERT_POSTS", [payload, analysis_status])
    connection.commit()


def query_posts(connection, platform, limit, before_seq=None, max_seq=None):
    """Stable insertion-order page; the first page fixes the capture sequence ceiling."""
    if isinstance(connection, ObjectControlStore):
        return control_store.query_posts(connection, platform, limit, before_seq, max_seq)
    import oracledb
    if (platform is not None and platform not in ("x", "facebook", "instagram", "tiktok")
            or type(limit) is not int or not 1 <= limit <= 100
            or any(value is not None and (type(value) is not int or value < minimum)
                   for value, minimum in ((before_seq, 1), (max_seq, 0)))):
        raise ValueError("Invalid post pagination")
    result = connection.cursor().callfunc("ADMIN.PRISMA_CONTROL.LIST_POSTS", oracledb.DB_TYPE_CLOB,
                                          [platform, limit, before_seq, max_seq])
    document = json.loads(result.read() if hasattr(result, "read") else result)
    items = [{**item["payload"], "capture_seq": item["capture_seq"], "analysis_status": item["analysis_status"],
              "captured_at": item.get("captured_at") or item["payload"].get("captured_at")}
             for item in document["items"][:limit]]
    return {**document, "items": items, "next_seq": items[-1]["capture_seq"] if len(document["items"]) > limit else None}


def query_ordered_posts(connection, platform, limit, position=None, maximum=None, sort="published_at", order="desc"):
    if isinstance(connection, ObjectControlStore):
        return control_store.query_ordered_posts(connection, platform, limit, position, maximum, sort, order)
    import oracledb
    if (platform is not None and platform not in ("x", "facebook", "instagram", "tiktok")
            or type(limit) is not int or not 1 <= limit <= 100 or sort not in {"published_at", "captured_at"}
            or order not in {"asc", "desc"} or maximum is not None and (type(maximum) is not int or maximum < 0)):
        raise ValueError("Invalid ordered post pagination")
    before, identity = position["key"] if position else (None, None)
    if before is not None:
        before = str(before).zfill(20) if sort == "captured_at" else before if before not in {"", "\uffff"} else "~" if order == "asc" else "!"
    try:
        result = connection.cursor().callfunc("ADMIN.PRISMA_CONTROL.LIST_ORDERED_POSTS", oracledb.DB_TYPE_CLOB,
                                              [platform, limit, before, identity, maximum, sort, order])
    except Exception as exc:
        error = exc.args[0] if exc.args else None
        # Rolling upgrades retain the original reader until the package is installed.
        if (getattr(error, "code", None) == 6550 and "PLS-00302" in str(error)
                and "LIST_ORDERED_POSTS" in str(error)):
            return None
        raise
    document = json.loads(result.read() if hasattr(result, "read") else result)
    # An older producer may still write during rollout; never sort its unnormalized dates.
    if document.get("projection_pending", 0):
        return None
    return {**document, "items": [{**row["payload"], "capture_seq": row["capture_seq"], "analysis_status": row["analysis_status"],
                                  "captured_at": row.get("captured_at") or row["payload"].get("captured_at")}
                                 for row in document["items"]]}
